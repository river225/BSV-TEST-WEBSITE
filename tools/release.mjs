#!/usr/bin/env node
/**
 * BlockSpin Values — release tool. Run before every push:
 *
 *   node tools/release.mjs                 regenerate pages + sitemap, stamp versions
 *   node tools/release.mjs --fetch-items   also refresh tools/items.json from the Sheet (GitHub Action)
 *   node tools/release.mjs --check         fail if anything is out of date (no writes)
 *   node tools/release.mjs --root=/BSV-TEST-WEBSITE/   build for a GitHub project-pages host
 *
 * What it does:
 *  1. Section, guide and item pages are generated from index.html, so they can never drift
 *     from the home page (same scripts, same chrome). Never edit files under values/, guides/,
 *     items/, richest-players/ or crew-logos/ by hand — edit index.html and re-run this.
 *  2. Every ?v= on every HTML page becomes a hash of that file's contents, so a visitor can
 *     never get an old cached copy of a changed file, and every page agrees on the version.
 *     window.BSV_ASSET_V carries the same hashes for scripts loaded later by site-chrome.js.
 *  3. sitemap.xml lists every real page.
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://blockspinvalues.com";
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const FETCH = args.includes("--fetch-items");
// tools/site.json exists only on the test site: {"root": "/BSV-TEST-WEBSITE/"} (never synced from main).
const SITE_FILE = path.join(ROOT, "tools", "site.json");
const SITE_SETTINGS = fs.existsSync(SITE_FILE) ? JSON.parse(fs.readFileSync(SITE_FILE, "utf8")) : {};
const ROOT_ARG = args.find((a) => a.startsWith("--root="));
const BASE = (ROOT_ARG ? ROOT_ARG.slice(7) : SITE_SETTINGS.root || "/").replace(/\/?$/, "/");
const ITEMS_FILE = path.join(ROOT, "tools", "items.json");
const GENERATED_DIRS = ["values", "guides", "items", "richest-players", "crew-logos"];
const GEN_MARK = "<!-- Generated by tools/release.mjs from index.html. Do not edit; edit index.html and re-run. -->";
const ITEM_SECTION_IDS = ["uncommon", "rare", "epic", "legendary", "omega", "misc", "vehicles", "untradeable-items"];
const GUIDE_TABS = [
  { key: "fishing", path: "guides/fishing/", title: "BlockSpin Fishing Guide – Fish Prices & Best Spots | BlockSpin Values",
    description: "Every fish in BlockSpin with sell prices, plus the best fishing methods to make money fast." },
  { key: "farming", path: "guides/farming/", title: "BlockSpin Farming Guide – Crops & Profits | BlockSpin Values",
    description: "BlockSpin farming guide: every crop, what it sells for and how to farm for the best profit." },
  { key: "quest", path: "guides/quests/", title: "BlockSpin Quest Guide – Every Quest Explained | BlockSpin Values",
    description: "Every BlockSpin quest explained step by step, with rewards and tips to finish them quickly." }
];
const EXTRA_SITEMAP_URLS = [
  "live-trading.html", "blockspin-discord-server.html", "sponsors/", "x-about.html", "x-faq.html",
  "x-richest-not-listed.html", "z-terms.html", "z-privacy.html", "z-cookie.html", "z-contact.html"
];

const changed = [];
function writeIfChanged(file, content) {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === content) return;
  changed.push(path.relative(ROOT, file));
  if (CHECK) return;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), "utf8");
const escHtml = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const escJsonInScript = (o) => JSON.stringify(o).replace(/</g, "\\u003c");

/* ---------- registry + config straight from the files the browser loads ---------- */
function loadBrowserGlobals(files) {
  const sandbox = {};
  sandbox.window = sandbox;
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  for (const f of files) vm.runInContext(read(f), sandbox, { filename: f });
  return sandbox;
}
const G = loadBrowserGlobals(["bsv-config.js", "section-config.js"]);
const REGISTRY = G.BSV_SECTION_REGISTRY;
const SPREADSHEET_ID = G.BSV_CONFIG.SPREADSHEET_ID;

/* ---------- Sheet → tools/items.json (same rules as script.js fetchSheet) ---------- */
const TRUE_REGEX = /^(yes|true|1|on|y)$/i;
const normKey = (s) => String(s || "").toLowerCase().replace(/[^a-z0-9]/g, "");
const cellValue = (c) => (!c ? "" : c.f != null && String(c.f).trim() !== "" ? c.f : c.v != null ? c.v : "");
function field(obj, key) {
  for (const k of Object.keys(obj)) {
    if (normKey(k) === key) {
      const v = obj[k];
      if (v != null && String(v).trim() !== "") return String(v).trim();
    }
  }
  return "";
}
async function fetchItems() {
  const out = [];
  for (const cfg of REGISTRY) {
    if (!ITEM_SECTION_IDS.includes(cfg.id)) continue;
    const sheet = cfg.sheetName || cfg.title;
    const url = `https://docs.google.com/spreadsheets/d/${SPREADSHEET_ID}/gviz/tq?tqx=out:json&sheet=${encodeURIComponent(sheet)}&headers=1`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Sheet ${sheet}: HTTP ${res.status}`);
    const text = await res.text();
    const json = JSON.parse(text.substring(text.indexOf("{"), text.lastIndexOf("}") + 1));
    const cols = json.table.cols.map((c) => (c.label || "").trim());
    let n = 0;
    for (const r of json.table.rows || []) {
      const row = {};
      cols.forEach((label, i) => { if (label) row[label] = cellValue(r.c && r.c[i]); });
      const name = String(row["Name"] || "").trim();
      if (!name || TRUE_REGEX.test(field(row, "hidden"))) continue;
      out.push({
        section: cfg.title,
        name,
        value: field(row, "averagevalue"),
        ranged: field(row, "rangedvalue"),
        demand: field(row, "demand"),
        image: field(row, "imageurl") || field(row, "image")
      });
      n++;
    }
    console.log(`  ${sheet}: ${n} items`);
  }
  return out;
}

/* ---------- slugs (keep identical to bsvBuildItemSlugIndex in script.js) ---------- */
function slugifyName(name) {
  return String(name || "").normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase()
    .replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}
function assignSlugs(items) {
  const bySlug = new Map();
  const seen = new Set();
  const out = [];
  for (const cfg of REGISTRY) {
    if (!ITEM_SECTION_IDS.includes(cfg.id)) continue;
    for (const it of items.filter((x) => x.section === cfg.title)) {
      const key = cfg.title + "|" + it.name;
      if (seen.has(key)) continue;
      const base = slugifyName(it.name);
      if (!base) continue;
      const slug = bySlug.has(base) ? `${base}-${cfg.id}` : base;
      if (bySlug.has(slug)) continue;
      seen.add(key);
      bySlug.set(slug, it);
      out.push({ ...it, slug, sectionId: cfg.id, sectionPath: cfg.path });
    }
  }
  return out;
}

/* ---------- page generation from index.html ---------- */
function setTag(html, re, replacement) {
  if (!re.test(html)) throw new Error("index.html is missing a tag the generator needs: " + re);
  return html.replace(re, replacement);
}
function buildPage(template, page) {
  let h = template;
  const url = SITE + "/" + page.path;
  h = setTag(h, /<title>[\s\S]*?<\/title>/, `<title>${escHtml(page.title)}</title>`);
  h = setTag(h, /<meta name="description" content="[^"]*">/, `<meta name="description" content="${escHtml(page.description)}">`);
  h = setTag(h, /<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${escHtml(page.description)}">`);
  h = setTag(h, /<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${escHtml(page.title)}">`);
  h = /<meta property="og:url" content="[^"]*">/.test(h)
    ? h.replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${escHtml(url)}">`)
    : h.replace("</title>", `</title>\n<meta property="og:url" content="${escHtml(url)}">`);
  h = setTag(h, /<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${escHtml(url)}" />`);
  if (page.image) {
    h = setTag(h, /<meta property="og:image" content="[^"]*">/,
      `<meta property="og:image" content="${escHtml(page.image)}">\n<meta property="og:image:width" content="1200">\n<meta property="og:image:height" content="630">\n<meta name="twitter:card" content="summary_large_image">`);
  }
  // Structured data: breadcrumb for this page instead of the home page's blocks.
  h = h.replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\s*/g, "");
  const crumbs = [{ name: "BlockSpin Values", url: SITE + "/" }, ...page.crumbs];
  const ld = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((c, i) => ({ "@type": "ListItem", position: i + 1, name: c.name, item: c.url }))
  };
  h = h.replace("</head>", `<script type="application/ld+json">${escJsonInScript(ld)}</script>\n</head>`);
  // Route + no-flash boot (same mechanism as #sec= deep links).
  const boot =
    `${GEN_MARK}\n<script>window.BSV_ROUTE=${escJsonInScript(page.route)};` +
    `document.documentElement.classList.add("bsv-hash-section");</script>\n` +
    `<style id="bsv-hash-section-style">#home{display:none!important}</style>`;
  h = setTag(h, /<head>/, `<head>\n${boot}`);
  // Section pages start on their section, not Home (avoids a layout jump when script removes it).
  h = h.replace('<body data-bsv-page="home" class="is-home">', '<body data-bsv-page="home">');
  // Page lives in a sub-folder: make every relative URL site-rooted.
  h = h.replace(/(\s(?:src|href)=")(?!https?:|\/\/|\/|#|data:|mailto:|javascript:|tel:)([^"]+)"/g, (m, a, u) => `${a}${BASE}${u}"`);
  return h;
}
function sectionPages() {
  const pages = [];
  for (const cfg of REGISTRY) {
    if (typeof cfg.path !== "string" || !cfg.path) continue;
    pages.push({
      path: cfg.path, title: cfg.seoTitle, description: cfg.seoDescription,
      route: { section: cfg.title },
      crumbs: [{ name: cfg.title, url: SITE + "/" + cfg.path }]
    });
  }
  const guide = REGISTRY.find((c) => c.id === "money-game-guide");
  for (const t of GUIDE_TABS) {
    pages.push({
      path: t.path, title: t.title, description: t.description,
      route: { section: guide.title, guide: t.key },
      crumbs: [{ name: guide.title, url: SITE + "/" + guide.path }, { name: t.title.split(" – ")[0], url: SITE + "/" + t.path }]
    });
  }
  return pages;
}
function itemDescription(it) {
  const parts = [];
  if (it.value) parts.push(`Average Value: ${it.value}`);
  if (it.ranged) parts.push(`Ranged Value: ${it.ranged}`);
  if (it.demand) parts.push(`Demand: ${it.demand}`);
  const stats = parts.length ? parts.join(" · ") + ". " : "";
  return (`${it.name} BlockSpin value. ${stats}Live ${it.section} values from BlockSpin Values.`).slice(0, 300);
}
function itemPages(items) {
  return items.map((it) => ({
    path: `items/${it.slug}/`,
    title: `${it.name} Value in BlockSpin | BlockSpin Values`,
    description: itemDescription(it),
    // Watermarked BlockSpin Values preview card drawn by the bot (share.blockspinvalues.com).
    image: `https://share.blockspinvalues.com/i/${it.slug}.png`,
    route: { section: it.section, item: it.name },
    crumbs: [
      { name: it.section, url: SITE + "/" + it.sectionPath },
      { name: it.name, url: SITE + `/items/${it.slug}/` }
    ]
  }));
}

/* ---------- versions: hash every asset, stamp every HTML ---------- */
function listFiles(dir, pred, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith(".") || e.name === "node_modules") continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) listFiles(p, pred, acc);
    else if (pred(p)) acc.push(p);
  }
  return acc;
}
const hashCache = new Map();
function fileHash(abs) {
  if (!hashCache.has(abs)) {
    hashCache.set(abs, crypto.createHash("sha256").update(fs.readFileSync(abs)).digest("hex").slice(0, 10));
  }
  return hashCache.get(abs);
}
function stampVersions(htmlAbs, html, manifestLine) {
  const dir = path.dirname(htmlAbs);
  let out = html.replace(/((?:src|href)=")([^"?#]+)\?v=[^"]*"/g, (m, a, u) => {
    if (/^(https?:)?\/\//.test(u)) return m;
    let rel = u;
    if (rel.startsWith(BASE)) rel = rel.slice(BASE.length);
    const abs = u.startsWith("/") ? path.join(ROOT, rel.replace(/^\//, "")) : path.join(dir, u);
    if (!fs.existsSync(abs)) return m;
    return `${a}${u}?v=${fileHash(abs)}"`;
  });
  out = out.replace(/\n?window\.BSV_ASSET_V = \{[^\n]*\};/g, "");
  out = out.replace(/window\.BSV_BUILD = "[^"]*";/, (m) => `${manifestLine}`);
  return out;
}

/* ---------- main ---------- */
async function main() {
  let items = fs.existsSync(ITEMS_FILE) ? JSON.parse(fs.readFileSync(ITEMS_FILE, "utf8")) : [];
  if (FETCH) {
    console.log("Fetching items from the Sheet…");
    const fresh = await fetchItems();
    // Safety: a half-empty Sheet (mid-edit, tab renamed) must never wipe item pages.
    if (fresh.length < 20 || (items.length && fresh.length < items.length * 0.6)) {
      throw new Error(`Refusing to update: Sheet returned ${fresh.length} items (had ${items.length}).`);
    }
    items = fresh;
    writeIfChanged(ITEMS_FILE, JSON.stringify(items, null, 1) + "\n");
  }
  const slugged = assignSlugs(items);

  const template = read("index.html");
  const pages = [...sectionPages(), ...itemPages(slugged)];

  // Versions first: assets do not depend on HTML, so hashes are final before any page is written.
  const assets = listFiles(ROOT, (p) => /\.(js|css)$/.test(p) && path.dirname(p) === ROOT);
  const manifest = {};
  for (const a of assets.sort()) manifest[path.basename(a)] = fileHash(a);
  const buildId = crypto.createHash("sha256").update(JSON.stringify(manifest)).digest("hex").slice(0, 10);
  const manifestLine = `window.BSV_BUILD = "${buildId}";\nwindow.BSV_ASSET_V = ${JSON.stringify(manifest)};`;

  const wanted = new Set();
  for (const p of pages) {
    const file = path.join(ROOT, p.path, "index.html");
    wanted.add(file);
    writeIfChanged(file, stampVersions(file, buildPage(template, p), manifestLine));
  }
  // Remove generated pages that no longer exist (e.g. an item was hidden or renamed).
  for (const d of GENERATED_DIRS) {
    const abs = path.join(ROOT, d);
    if (!fs.existsSync(abs)) continue;
    for (const f of listFiles(abs, (p) => p.endsWith(".html"))) {
      if (wanted.has(f)) continue;
      if (!fs.readFileSync(f, "utf8").includes(GEN_MARK)) continue; // never touch hand-made files
      changed.push("removed " + path.relative(ROOT, f));
      if (!CHECK) {
        fs.unlinkSync(f);
        try { fs.rmdirSync(path.dirname(f)); } catch (_) {}
      }
    }
  }
  // Every other HTML page: stamp versions in place.
  for (const html of listFiles(ROOT, (p) => p.endsWith(".html"))) {
    if (wanted.has(html)) continue;
    const cur = fs.readFileSync(html, "utf8");
    if (cur.includes(GEN_MARK)) continue;
    writeIfChanged(html, stampVersions(html, cur, manifestLine));
  }

  // Sitemap
  const urls = ["", ...EXTRA_SITEMAP_URLS, ...pages.map((p) => p.path)];
  const sitemap =
    `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls.map((u) => `  <url><loc>${SITE}/${u}</loc></url>`).join("\n") + `\n</urlset>\n`;
  writeIfChanged(path.join(ROOT, "sitemap.xml"), sitemap);

  const nItems = slugged.length;
  if (CHECK) {
    if (changed.length) {
      console.error(`Out of date (${changed.length}): ${changed.slice(0, 12).join(", ")}${changed.length > 12 ? "…" : ""}`);
      console.error("Run: node tools/release.mjs");
      process.exit(1);
    }
    console.log(`Up to date: ${pages.length} pages (${nItems} items).`);
  } else {
    console.log(`${pages.length} pages (${nItems} items). ${changed.length} file(s) updated.`);
  }
}
main().catch((e) => { console.error(e.message || e); process.exit(1); });
